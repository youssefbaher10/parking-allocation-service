
// Prepare the local environment for Cognito authentication.
// Existing environment settings are preserved.

const fs = require("node:fs");
const path = require("node:path");
const { randomBytes } = require("node:crypto");
const dotenv = require("dotenv");

function createDemo(root = ".") {
  const folder = path.join(root, ".local");

  fs.mkdirSync(folder, {
    recursive: true,
    mode: 0o700,
  });

  const file = path.join(root, ".env");

  const current = fs.existsSync(file)
    ? dotenv.parse(fs.readFileSync(file))
    : {};

  const defaults = {
    PORT: "3001",
    AWS_REGION: "us-east-1",
    AWS_PROFILE: "floci",
    DYNAMODB_ENDPOINT: "http://localhost:4566",
    PARKING_REQUESTS_TABLE: "ParkingRequests",
    INVENTORY_MODE: "sample",

    // Internal microservice authentication
    INTERNAL_TOKEN: randomBytes(48).toString("hex"),

    // Cognito authentication
    AUTH_MODE: "cognito",
    COGNITO_REGION: "us-east-1",
    COGNITO_ENDPOINT: "http://localhost:4566",
    COGNITO_USERS_FILE: ".local/cognito-users.json",
  };

  // Read Cognito configuration generated by the deployment script
  const cognitoPath = path.join(
    folder,
    "runtime",
    "cognito.json"
  );

  if (fs.existsSync(cognitoPath)) {
    const cognito = JSON.parse(
      fs.readFileSync(cognitoPath, "utf8")
    );

    if (cognito.userPoolId && cognito.clientId) {
      defaults.COGNITO_REGION =
        cognito.region || "us-east-1";

      defaults.COGNITO_USER_POOL_ID = cognito.userPoolId;

      defaults.COGNITO_CLIENT_ID = cognito.clientId;

      defaults.COGNITO_ISSUER =
        "http://floci:4566/" + cognito.userPoolId;

      defaults.COGNITO_JWKS_URL =
        "http://localhost:4566/" +
        cognito.userPoolId +
        "/.well-known/jwks.json";
    }
  }

  // Add missing environment variables only
  const lines = Object.entries(defaults)
    .filter(([key]) => !Object.hasOwn(current, key))
    .map(([key, value]) => key + "=" + value);

  if (lines.length) {
    fs.appendFileSync(
      file,
      "\n" + lines.join("\n") + "\n",
      { mode: 0o600 }
    );
  }

  console.log("Local environment configuration prepared.");

  const finalConfig = dotenv.parse(fs.readFileSync(file));

  const required = [
    "COGNITO_USER_POOL_ID",
    "COGNITO_CLIENT_ID",
    "COGNITO_ISSUER",
    "COGNITO_JWKS_URL",
  ];

  const missing = required.filter(
    (key) => !finalConfig[key]?.trim()
  );

  if (missing.length) {
    console.log("Cognito configuration is incomplete.");
    console.log("Missing variables:", missing.join(", "));
    console.log("Run infra/services/12-cognito.sh.");
  } else {
    console.log("Cognito configuration available.");
  }

  if (finalConfig.AUTH_MODE !== "cognito") {
    console.log("Set AUTH_MODE=cognito in your .env file.");
  }

  if (
    !fs.existsSync(
      path.resolve(root, finalConfig.COGNITO_USERS_FILE ||
        ".local/cognito-users.json")
    )
  ) {
    console.log("Cognito user identity mapping is required.");
  }

  console.log("User credentials are managed by Cognito.");
}

if (require.main === module) {
  createDemo();
}

module.exports = createDemo;
